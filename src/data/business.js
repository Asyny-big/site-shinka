/* ---------- маленькие помощники, общие для сборки и браузера ---------- */

export const rub = (n) => n.toLocaleString('ru-RU').replace(/ | /g, ' ');

/** «от 1 600 ₽» / «18 ₽» / «бесплатно» */
export function priceText(p) {
  if (p.amount == null) return p.text || 'уточняет мастер';
  return (p.from ? 'от ' : '') + rub(p.amount) + ' ₽';
}

export const serviceById = (id) => business.services.find((s) => s.id === id);

export function findPrice(id) {
  for (const s of business.services) {
    const p = s.prices.find((x) => x.id === id);
    if (p) return { service: s, price: p };
  }
  return null;
}

/** Минимальная числовая цена услуги — для подписи в навигации */
export function minPrice(service) {
  const nums = service.prices.filter((p) => p.amount != null);
  if (!nums.length) return null;
  return nums.reduce((a, b) => (b.amount < a.amount ? b : a));
}
